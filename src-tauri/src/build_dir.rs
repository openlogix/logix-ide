//! The temporary Apio project the IDE builds in. Plain Rust, no Tauri.
//!
//! Builds use the project's in-memory files, so unsaved edits are built
//! too. The folder is reused between builds of the same project, so Apio's
//! `_build/` output stays and repeated builds are faster.

use std::path::{Path, PathBuf};

use anyhow::{bail, Context, Result};

use crate::project::{self, ProjectFile, RESERVED_NAMES};

/// Pin constraint file extensions. Apio picks up the project's single
/// constraint file by itself.
pub const CONSTRAINT_EXTENSIONS: &[&str] = &["pcf", "lpf", "cst", "xdc", "pdc", "ccf"];

/// Records which project the folder was prepared for.
const KEY_FILE: &str = ".logix-build-key";
/// Apio puts this in the GTKWave layouts (.gtkw) it generates; files
/// without it were saved by the user from GTKWave.
const GTKW_AUTO_MARKER: &str = "THIS FILE WAS GENERATED AUTOMATICALLY BY APIO";
/// Apio's output folder, kept between builds.
const OUTPUT_DIR: &str = "_build";

pub struct BuildInput<'a> {
    /// Identifies the project (e.g. its folder). A different key starts
    /// from an empty folder.
    pub key: &'a str,
    /// Folder whose other files (e.g. memory init data) are copied too.
    pub source_dir: Option<&'a Path>,
    pub files: &'a [ProjectFile],
    pub board: &'a str,
}

/// The project's pin constraint file, if it has one.
pub fn constraint_file(files: &[ProjectFile]) -> Option<&str> {
    files.iter().map(|f| f.name.as_str()).find(|name| {
        Path::new(name)
            .extension()
            .and_then(|e| e.to_str())
            .is_some_and(|e| {
                CONSTRAINT_EXTENSIONS
                    .iter()
                    .any(|c| c.eq_ignore_ascii_case(e))
            })
    })
}

/// The `apio.ini` Logix generates: the board and top module `main`.
pub fn apio_ini(board: &str) -> String {
    format!(
        "; Generated by Logix. Changes are overwritten.\n\
         [env:default]\n\
         board = {board}\n\
         top-module = main\n"
    )
}

/// A prepared build folder.
pub struct Prepared {
    /// The folder to run Apio in.
    pub dir: PathBuf,
    /// Files and folders of the project left out of the build (Verilog and
    /// pin files in subfolders, nested projects); see `CopyMode::Build`.
    pub left_out: Vec<String>,
}

/// Fills `root` with the project's files and a generated `apio.ini`.
pub fn prepare(root: &Path, input: &BuildInput) -> Result<Prepared> {
    check_board(input.board)?;
    project::check_files(input.files)?;

    let key_path = root.join(KEY_FILE);
    let same_project = std::fs::read_to_string(&key_path).is_ok_and(|k| k == input.key);
    if !same_project && root.exists() {
        std::fs::remove_dir_all(root).with_context(|| format!("can't clear {}", root.display()))?;
    }
    std::fs::create_dir_all(root).with_context(|| format!("can't create {}", root.display()))?;

    // Remove everything from the previous build except Apio's output, so
    // deleted or renamed files don't linger.
    for entry in std::fs::read_dir(root)? {
        let entry = entry?;
        let name = entry.file_name();
        if name == OUTPUT_DIR || name == KEY_FILE {
            continue;
        }
        let path = entry.path();
        if path.is_dir() {
            std::fs::remove_dir_all(&path)?;
        } else {
            std::fs::remove_file(&path)?;
        }
    }

    let mut left_out = Vec::new();
    if let Some(source) = input.source_dir.filter(|d| d.is_dir()) {
        let skip: Vec<&str> = input
            .files
            .iter()
            .map(|f| f.name.as_str())
            .chain(RESERVED_NAMES.iter().copied())
            .collect();
        left_out = project::copy_project_contents(source, root, &skip, project::CopyMode::Build)?;
    }
    for f in input.files {
        project::write_atomic(&root.join(&f.name), f.text.as_bytes())?;
    }
    std::fs::write(root.join("apio.ini"), apio_ini(input.board))?;
    std::fs::write(&key_path, input.key)?;
    Ok(Prepared {
        dir: root.to_path_buf(),
        left_out,
    })
}

/// Fills `root` with a project holding just `file` and an `apio.ini` (for
/// `apio format`, which needs a project but not the other files). Returns
/// the folder to run Apio in.
pub fn prepare_single(root: &Path, file: &ProjectFile, board: &str) -> Result<PathBuf> {
    check_board(board)?;
    project::check_plain_file_name(&file.name)?;
    if root.exists() {
        std::fs::remove_dir_all(root).with_context(|| format!("can't clear {}", root.display()))?;
    }
    std::fs::create_dir_all(root).with_context(|| format!("can't create {}", root.display()))?;
    std::fs::write(root.join(&file.name), &file.text)?;
    std::fs::write(root.join("apio.ini"), apio_ini(board))?;
    Ok(root.to_path_buf())
}

/// Copies GTKWave layouts (.gtkw) the user saved from GTKWave in the build
/// folder back to the project folder `project_dir`, so they're kept (the
/// build folder is cleared before each run). Only if `root` was prepared
/// for the same project (`key`). Skips Apio's own generated layouts and
/// files the project already has unchanged. Returns the copied names.
pub fn save_back_gtkw(root: &Path, key: &str, project_dir: &Path) -> Result<Vec<String>> {
    let same_project = std::fs::read_to_string(root.join(KEY_FILE)).is_ok_and(|k| k == key);
    if !same_project || !project_dir.is_dir() {
        return Ok(Vec::new());
    }
    let mut copied = Vec::new();
    for entry in std::fs::read_dir(root)? {
        let entry = entry?;
        let name = entry.file_name().to_string_lossy().into_owned();
        let is_gtkw = Path::new(&name)
            .extension()
            .is_some_and(|e| e.eq_ignore_ascii_case("gtkw"));
        if !is_gtkw || !entry.path().is_file() {
            continue;
        }
        let text = std::fs::read(entry.path())?;
        if String::from_utf8_lossy(&text).contains(GTKW_AUTO_MARKER) {
            continue;
        }
        let target = project_dir.join(&name);
        if std::fs::read(&target).is_ok_and(|existing| existing == text) {
            continue;
        }
        project::write_atomic(&target, &text)?;
        copied.push(name);
    }
    copied.sort();
    Ok(copied)
}

/// The board id ends up in `apio.ini`; keep it plain.
fn check_board(board: &str) -> Result<()> {
    let ok = !board.is_empty()
        && board
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.'));
    if !ok {
        bail!("invalid board id: {board:?}");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn file(name: &str, text: &str) -> ProjectFile {
        ProjectFile {
            name: name.into(),
            text: text.into(),
        }
    }

    fn names(dir: &Path) -> Vec<String> {
        let mut v: Vec<_> = std::fs::read_dir(dir)
            .unwrap()
            .flatten()
            .map(|e| e.file_name().to_string_lossy().into_owned())
            .collect();
        v.sort();
        v
    }

    #[test]
    fn writes_files_and_apio_ini() {
        let tmp = tempfile::tempdir().unwrap();
        let root = tmp.path().join("build");
        let files = [file("main.v", "m"), file("pinout.pcf", "p")];
        let dir = prepare(
            &root,
            &BuildInput {
                key: "/p/a",
                source_dir: None,
                files: &files,
                board: "alhambra-ii",
            },
        )
        .unwrap()
        .dir;
        assert_eq!(
            names(&dir),
            [".logix-build-key", "apio.ini", "main.v", "pinout.pcf"]
        );
        let ini = std::fs::read_to_string(dir.join("apio.ini")).unwrap();
        assert!(ini.contains("board = alhambra-ii\n"));
        assert!(ini.contains("top-module = main\n"));
    }

    #[test]
    fn keeps_output_for_same_project_and_drops_stale_files() {
        let tmp = tempfile::tempdir().unwrap();
        let root = tmp.path().join("build");
        let two = [file("main.v", "x"), file("old.v", "x")];
        let one = [file("main.v", "x")];
        let input = |key, files| BuildInput {
            key,
            source_dir: None,
            files,
            board: "b",
        };

        prepare(&root, &input("k1", &two)).unwrap();
        std::fs::create_dir_all(root.join("_build")).unwrap();

        prepare(&root, &input("k1", &one)).unwrap();
        assert!(root.join("_build").exists(), "same project keeps output");
        assert!(!root.join("old.v").exists(), "removed files are dropped");

        prepare(&root, &input("k2", &one)).unwrap();
        assert!(
            !root.join("_build").exists(),
            "another project starts clean"
        );
    }

    #[test]
    fn copies_other_source_files_but_not_ide_files() {
        let tmp = tempfile::tempdir().unwrap();
        let src = tmp.path().join("src");
        std::fs::create_dir_all(src.join("_build")).unwrap();
        for (name, text) in [
            ("main.v", "on disk"),
            ("rom.hex", "00"),
            ("apio.ini", "old"),
            ("logix.json", "{}"),
            (".hidden", "x"),
        ] {
            std::fs::write(src.join(name), text).unwrap();
        }
        let root = tmp.path().join("build");
        let files = [file("main.v", "in memory")];
        prepare(
            &root,
            &BuildInput {
                key: "k",
                source_dir: Some(&src),
                files: &files,
                board: "b",
            },
        )
        .unwrap();
        assert_eq!(
            std::fs::read_to_string(root.join("main.v")).unwrap(),
            "in memory"
        );
        assert_eq!(std::fs::read_to_string(root.join("rom.hex")).unwrap(), "00");
        assert!(std::fs::read_to_string(root.join("apio.ini"))
            .unwrap()
            .contains("board = b"));
        assert!(!root.join("logix.json").exists());
        assert!(!root.join(".hidden").exists());
        assert!(!root.join("_build").exists());
    }

    #[test]
    fn leaves_out_sources_in_subfolders_and_nested_projects() {
        let tmp = tempfile::tempdir().unwrap();
        let src = tmp.path().join("proj");
        for (name, text) in [
            ("main.v", "on disk"),
            ("data/rom.hex", "00"),
            ("data/old.v", "module old; endmodule"),
            ("data/pins.pcf", "set_io a 1"),
            ("copy/logix.json", "{}"),
            ("copy/main.v", "module main; endmodule"),
            ("copy/notes.txt", "hi"),
        ] {
            let path = src.join(name);
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(path, text).unwrap();
        }
        let root = tmp.path().join("build");
        let files = [file("main.v", "in memory")];
        let prepared = prepare(
            &root,
            &BuildInput {
                key: "k",
                source_dir: Some(&src),
                files: &files,
                board: "b",
            },
        )
        .unwrap();
        assert_eq!(prepared.left_out, ["copy/", "data/old.v", "data/pins.pcf"]);
        assert!(root.join("data/rom.hex").exists());
        assert!(!root.join("data/old.v").exists());
        assert!(!root.join("copy").exists());
    }

    #[test]
    fn rejects_bad_input() {
        let tmp = tempfile::tempdir().unwrap();
        let ok_files = [file("main.v", "m")];
        let bad_board = BuildInput {
            key: "k",
            source_dir: None,
            files: &ok_files,
            board: "x\ny = 1",
        };
        assert!(prepare(tmp.path(), &bad_board).is_err());
        let no_main = [file("other.v", "x")];
        let bad_files = BuildInput {
            key: "k",
            source_dir: None,
            files: &no_main,
            board: "b",
        };
        assert!(prepare(tmp.path(), &bad_files).is_err());
    }

    #[test]
    fn saves_back_user_gtkwave_layouts() {
        let tmp = tempfile::tempdir().unwrap();
        let root = tmp.path().join("build");
        let project = tmp.path().join("project");
        std::fs::create_dir_all(&project).unwrap();
        let files = [file("main.v", "m")];
        prepare(
            &root,
            &BuildInput {
                key: "p1",
                source_dir: None,
                files: &files,
                board: "b",
            },
        )
        .unwrap();
        // What `apio sim` and GTKWave leave behind.
        std::fs::write(
            root.join("auto_tb.gtkw"),
            format!("[*] {GTKW_AUTO_MARKER}.\nx\n"),
        )
        .unwrap();
        std::fs::write(root.join("main_tb.gtkw"), "[*] user layout\n").unwrap();
        std::fs::write(root.join("same_tb.gtkw"), "same").unwrap();
        std::fs::write(project.join("same_tb.gtkw"), "same").unwrap();

        // Another project's build folder: nothing is copied.
        assert!(save_back_gtkw(&root, "p2", &project).unwrap().is_empty());

        let copied = save_back_gtkw(&root, "p1", &project).unwrap();
        assert_eq!(copied, ["main_tb.gtkw"]);
        assert_eq!(
            std::fs::read_to_string(project.join("main_tb.gtkw")).unwrap(),
            "[*] user layout\n"
        );
        assert!(!project.join("auto_tb.gtkw").exists());
        // Unchanged since: nothing more to copy.
        assert!(save_back_gtkw(&root, "p1", &project).unwrap().is_empty());
    }

    #[test]
    fn single_file_project() {
        let tmp = tempfile::tempdir().unwrap();
        let root = tmp.path().join("format");
        std::fs::create_dir_all(&root).unwrap();
        std::fs::write(root.join("stale.v"), "x").unwrap();
        let dir = prepare_single(&root, &file("alu.v", "module alu; endmodule"), "b").unwrap();
        assert_eq!(names(&dir), ["alu.v", "apio.ini"]);
        assert!(prepare_single(&root, &file("../x.v", ""), "b").is_err());
    }

    #[test]
    fn finds_constraint_file() {
        assert_eq!(
            constraint_file(&[file("main.v", ""), file("Pins.PCF", "")]),
            Some("Pins.PCF")
        );
        assert_eq!(constraint_file(&[file("main.v", "")]), None);
    }
}
